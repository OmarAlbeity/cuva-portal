/* =====================================================================
 * Builds public/vendor/icons.js — only the Lucide icons the site uses
 * (a few KB instead of the full ~450 KB library, and no CDN needed).
 *
 *   npm run build:icons
 *
 * It scans public/ for data-lucide="name" and icon: 'name' / icon = 'name'.
 * ===================================================================== */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const lucideDir = dirname(require.resolve('lucide/package.json'));
const lucideVersion = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8')).version;

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === 'vendor' ? [] : walk(full);
    return /\.(html|js)$/.test(name) ? [full] : [];
  });
}

const names = new Set();
for (const file of walk(join(root, 'public'))) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(m[1]);
  for (const m of src.matchAll(/icon\s*[:=]\s*'([a-z0-9-]+)'/g)) names.add(m[1]);
}

// Icons and their aliases (e.g. "trash-2" → Trash2), keyed by PascalCase name
const all = await import(pathToFileURL(join(lucideDir, 'dist', 'esm', 'iconsAndAliases.mjs')).href);
const toPascal = name => name.split('-').map(p => p.charAt(0).toUpperCase() + p.slice(1)).join('');

const icons = {};
for (const name of [...names].sort()) {
  const node = all[toPascal(name)];
  if (!Array.isArray(node)) {
    console.error(`Unknown Lucide icon: "${name}"`);
    process.exit(1);
  }
  icons[name] = node;
}

const out = `/* Generated by tools/build-icons.mjs from lucide v${lucideVersion} (ISC license, https://lucide.dev). Do not edit. */
(function () {
  'use strict';
  var ICONS = ${JSON.stringify(icons)};
  var NS = 'http://www.w3.org/2000/svg';
  var ATTRS = { xmlns: NS, width: 24, height: 24, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor',
    'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true' };

  function build(name, node, cls) {
    var svg = document.createElementNS(NS, 'svg');
    for (var k in ATTRS) svg.setAttribute(k, ATTRS[k]);
    svg.setAttribute('class', ('lucide lucide-' + name + ' ' + (cls || '')).trim());
    node.forEach(function (child) {
      var el = document.createElementNS(NS, child[0]);
      for (var a in child[1]) el.setAttribute(a, child[1][a]);
      svg.appendChild(el);
    });
    return svg;
  }

  function createIcons() {
    document.querySelectorAll('i[data-lucide]').forEach(function (el) {
      var name = el.getAttribute('data-lucide');
      var node = ICONS[name];
      if (!node) { console.warn('CUVA icons: missing icon "' + name + '" (run npm run build:icons)'); return; }
      el.parentNode.replaceChild(build(name, node, el.getAttribute('class')), el);
    });
  }

  window.lucide = { createIcons: createIcons };
})();
`;

writeFileSync(join(root, 'public', 'vendor', 'icons.js'), out);
console.log(`Built public/vendor/icons.js with ${Object.keys(icons).length} icons: ${Object.keys(icons).join(', ')}`);
